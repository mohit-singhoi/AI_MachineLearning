#  Operatrors in Python

# Arithmetic Operators
a = 15
b = 4
print("Addition:", a + b)          # Addition
print("Subtraction:", a - b)       # Subtraction
print("Multiplication:", a * b)    # Multiplication
print("Division:", a / b)          # Division
print("Floor Division:", a // b)   # Floor Division
print("Modulus:", a % b)           # Modulus
print("Exponentiation:", a ** b)   # Exponentiation
print("\n" )


# Comparison Operators  
x = 10
y = 20
print("Equal:", x == y)            # Equal
print("Not Equal:", x != y)        # Not Equal
print("Greater than:", x > y)      # Greater than
print("Less than:", x < y)         # Less than
print("Greater than or equal to:", x >= y)  # Greater than or equal to
print("Less than or equal to:", x <= y)     # Less than or equal to 
print("\n")

# Logical Operators
p = True
q = False
print("Logical AND:", p and q)     # Logical AND
print("Logical OR:", p or q)       # Logical OR
print("Logical NOT:", not p)       # Logical NOT 
print("\n")

# Assignment Operators
m = 5
m += 3  # Equivalent to m = m + 3
print("After += :", m)
m -= 2  # Equivalent to m = m - 2
print("After -= :", m)
m *= 4  # Equivalent to m = m * 4
print("After *= :", m)
m /= 2  # Equivalent to m = m / 2
print("After /= :", m)  
print("\n")

# Unary Operators
n = 10
print("Unary Plus:", +n)           # Unary Plus
print("Unary Minus:", -n)          # Unary Minus
print("\n")

# Bitwise Operators
a = 5  # In binary: 0101
b = 3  # In binary: 0011
print("Bitwise AND:", a & b)      # Bitwise AND
print("Bitwise OR:", a | b)       # Bitwise OR
print("Bitwise XOR:", a ^ b)      # Bitwise XOR
print("Bitwise NOT:", ~a)         # Bitwise NOT
print("Left Shift:", a << 1)      # Left Shift
print("Right Shift:", a >> 1)     # Right Shift
print("\n")


# Membership Operators
list1 = [1, 2, 3, 4, 5]
print("Is 3 in list1?:", 3 in list1)        # Membership
print("Is 6 not in list1?:", 6 not in list1)  # Membership  
print("\n")


# Identity Operators
x = 10
y = 10
print("Is x identical to y?:", x is y)        # Identity
print("Is x not identical to y?:", x is not y)  # Identity
print("\n")

   

