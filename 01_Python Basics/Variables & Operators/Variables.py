# 1. Integer variable
age = 21
print("Age:", age)
print("Type of age:", type(age))

# 2. Float variable
height = 5.7
print("Height:", height)
print("Type of height:", type(height))

# 3. String variable
name = "Mohit Kumar"
print("Name:", name)
print("Type of name:", type(name))

# 4. Boolean variable
is_student = True
print("Is Student:", is_student)
print("Type of is_student:", type(is_student))

# 5. Complex variable
complex_number = 3 + 4j
print("Complex Number:", complex_number)
print("Type of complex_number:", type(complex_number))

# 6. Multiple Assignment Program
x, y, z = 10, 20.5, "Hello"
print("x:", x, "Type of x:", type(x))
print("y:", y, "Type of y:", type(y))
print("z:", z, "Type of z:", type(z))


# 7. Variable Reassignment
var = 100
print("Initial var:", var, "Type of var:", type(var))
var = "Now I'm a string"
print("Reassigned var:", var, "Type of var:", type(var))


# 8. Constants (by convention)
PI = 3.14159
print("Value of PI:", PI, "Type of PI:", type(PI))


# 9. Using type() function to check variable types
a = 42
b = 3.14
c = "Python"
print("Type of a:", type(a))
print("Type of b:", type(b))
print("Type of c:", type(c))


# 10. Dynamic typing program
x = 10
print(x, type(x))
x = "Hello"
print(x, type(x))


